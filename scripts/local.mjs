#!/usr/bin/env node
/**
 * Local test network helper: a fork of X Layer mainnet under chain id 31337.
 * Cross-platform (Windows cmd/PowerShell, macOS, Linux).
 *
 *   npm run local:chain             start the fork (keep this terminal open)
 *   npm run local:deploy            deploy Lineage + founders to the fork, write apps/web/.env.local
 *   npm run local:fund -- 0xYOU     give your wallet 10 test OKB on the fork
 *
 * Why 31337 and not 196: wallets already know 196 as real X Layer, so a fork
 * reusing it could route "test" transactions to mainnet with real funds.
 */
import { spawn } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { encodeAbiParameters, isAddress, keccak256, numberToHex, pad, parseEther } from 'viem';
import { generatePrivateKey, privateKeyToAccount } from 'viem/accounts';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const PORT = Number(process.env.LOCAL_PORT ?? 8545);
const LOCAL_RPC = `http://127.0.0.1:${PORT}`;
const UPSTREAM = process.env.XLAYER_RPC ?? 'https://rpc.xlayer.tech';
const LOCAL_CHAIN_ID = 31337;
const BEM = '0x60e62Efa9405d6873C5deaBD4E6CC91c25363952';
const BEM_BALANCES_SLOT = 5n; // ERC-20 balances mapping slot, found with forge's stdstorage
const ENV_FILE = join(ROOT, 'apps/web/.env.local');
const ENV_MARKER = '# generated by `npm run local:deploy`';

const [command, ...args] = process.argv.slice(2);
const commands = { chain, deploy, fund, 'test-contracts': testContracts, 'test-fork': testFork };

if (!commands[command]) {
  console.error('Usage: node scripts/local.mjs <chain | deploy | fund 0xADDRESS [okb] | test-contracts | test-fork>');
  process.exit(1);
}
commands[command](...args).catch((err) => {
  console.error(`\n✗ ${err.message}`);
  process.exit(1);
});

async function chain() {
  console.log(`Forking X Layer mainnet as local chain ${LOCAL_CHAIN_ID} on ${LOCAL_RPC}`);
  console.log('Keep this terminal open. Ctrl+C stops the chain (all local state is discarded).\n');
  await run(foundry('anvil'), ['--fork-url', UPSTREAM, '--chain-id', String(LOCAL_CHAIN_ID), '--port', String(PORT)]);
}

async function deploy() {
  await assertLocalChain();

  // Throwaway deployer that exists only on this fork, funded via anvil cheatcodes.
  const key = generatePrivateKey();
  const deployer = privateKeyToAccount(key).address;
  await rpc('anvil_setBalance', [deployer, numberToHex(parseEther('100'))]);
  await rpc('anvil_setStorageAt', [BEM, bemBalanceSlot(deployer), pad(numberToHex(10n ** 8n))]); // 1 BEM
  console.log(`Deployer ${deployer} funded with 100 test OKB and 1 test BEM.\n`);

  const output = await run(
    foundry('forge'),
    ['script', 'script/Deploy.s.sol', '--rpc-url', LOCAL_RPC, '--private-key', key, '--broadcast'],
    { cwd: join(ROOT, 'contracts'), env: { ...process.env, NAND_STOCK: process.env.NAND_STOCK ?? '20000' }, capture: true },
  );
  const lineage = output.match(/lineage\s+(0x[0-9a-fA-F]{40})/)?.[1];
  if (!lineage) throw new Error('Deploy finished but the Lineage address was not found in the output.');

  writeEnv(lineage);
  console.log(`\n✓ Lineage deployed at ${lineage}`);
  console.log('Next: npm run local:fund -- <your wallet address>, then npm run dev');
}

async function fund(address, okb = '10') {
  if (!address || !isAddress(address)) throw new Error('Pass your wallet address: npm run local:fund -- 0xYourAddress');
  await assertLocalChain();
  await rpc('anvil_setBalance', [address, numberToHex(parseEther(okb))]);
  console.log(`✓ ${address} now has ${okb} test OKB on the local chain.`);
}

/** Unit tests with mocks; offline. */
async function testContracts() {
  await run(foundry('forge'), ['test', '--no-match-contract', 'Fork'], { cwd: join(ROOT, 'contracts') });
}

/** Real TapeOut contracts on a throwaway fork of X Layer mainnet; needs internet, spends nothing. */
async function testFork() {
  await run(foundry('forge'), ['test', '--match-contract', 'Fork', '-vv'], {
    cwd: join(ROOT, 'contracts'),
    env: { ...process.env, XLAYER_RPC: UPSTREAM },
  });
}

// ------------------------------------------------------------------ helpers

async function assertLocalChain() {
  let id;
  try {
    id = Number(await rpc('eth_chainId', []));
  } catch {
    throw new Error(`No local chain at ${LOCAL_RPC}. Start it first in another terminal: npm run local:chain`);
  }
  if (id !== LOCAL_CHAIN_ID) throw new Error(`Refusing: ${LOCAL_RPC} is chain ${id}, not the local fork (${LOCAL_CHAIN_ID}).`);
}

function bemBalanceSlot(account) {
  return keccak256(encodeAbiParameters([{ type: 'address' }, { type: 'uint256' }], [account, BEM_BALANCES_SLOT]));
}

function writeEnv(lineage) {
  const content = `${ENV_MARKER}\nVITE_LINEAGE_ADDRESS=${lineage}\nVITE_RPC_URL=${LOCAL_RPC}\nVITE_CHAIN_ID=${LOCAL_CHAIN_ID}\n`;
  if (existsSync(ENV_FILE) && !readFileSync(ENV_FILE, 'utf8').startsWith(ENV_MARKER)) {
    const alt = `${ENV_FILE}.local-fork`;
    writeFileSync(alt, content);
    console.log(`\n! apps/web/.env.local has your own settings, so I left it alone and wrote ${alt}. Copy it over to test locally.`);
    return;
  }
  writeFileSync(ENV_FILE, content);
  console.log(`\nWrote apps/web/.env.local (points the web app at the local chain).`);
}

async function rpc(method, params) {
  const res = await fetch(LOCAL_RPC, {
    method: 'POST',
    headers: { 'content-type': 'application/json' },
    body: JSON.stringify({ jsonrpc: '2.0', id: 1, method, params }),
  });
  const json = await res.json();
  if (json.error) throw new Error(`${method}: ${json.error.message}`);
  return json.result;
}

/** Foundry binaries are often only on Git Bash's PATH on Windows; fall back to ~/.foundry/bin. */
function foundry(name) {
  const exe = process.platform === 'win32' ? `${name}.exe` : name;
  const local = join(homedir(), '.foundry', 'bin', exe);
  return existsSync(local) ? local : name;
}

function run(cmd, cmdArgs, { cwd = ROOT, env = process.env, capture = false } = {}) {
  return new Promise((resolvePromise, reject) => {
    const child = spawn(cmd, cmdArgs, { cwd, env, stdio: capture ? ['inherit', 'pipe', 'inherit'] : 'inherit' });
    let out = '';
    child.stdout?.on('data', (d) => {
      out += d;
      process.stdout.write(d);
    });
    child.on('error', (err) =>
      reject(err.code === 'ENOENT' ? new Error(`${cmd} not found. Install Foundry: https://book.getfoundry.sh/getting-started/installation`) : err),
    );
    child.on('close', (code) => (code === 0 ? resolvePromise(out) : reject(new Error(`${cmd} exited with code ${code}`))));
  });
}
